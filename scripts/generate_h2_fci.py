"""Generate independent nonrelativistic BO H2 FCI/cc-pVTZ targets.

Requires PySCF, NumPy and SciPy. Gradients are analytic full-active-space
CASCI (equivalent to FCI), including the finite Gaussian basis Pulay terms.
No xTB outputs, pretrained models or experimental fitting data enter targets.
"""
import argparse
import hashlib
import importlib.metadata
import json
import platform
from pathlib import Path

import numpy as np
from pyscf import gto, lib, mcscf, scf


def reference(distance, basis):
    mol = gto.M(atom=f"H 0 0 0; H {distance:.12f} 0 0", unit="Angstrom",
                basis=basis, charge=0, spin=0, symmetry=False, verbose=0)
    mean_field = scf.RHF(mol)
    mean_field.conv_tol = 1e-12
    mean_field.max_cycle = 200
    mean_field.kernel()
    if not mean_field.converged:
        raise RuntimeError(f"RHF failed at R={distance}")
    solver = mcscf.CASCI(mean_field, mean_field.mo_coeff.shape[1], 2)
    solver.fcisolver.conv_tol = 1e-12
    solver.max_memory = 1500
    solver.kernel()
    if not solver.fcisolver.converged:
        raise RuntimeError(f"FCI failed at R={distance}")
    gradient = solver.nuc_grad_method().kernel()
    if not np.isfinite(gradient).all() or np.max(np.abs(gradient.sum(axis=0))) > 1e-8:
        raise RuntimeError("invalid independent FCI gradient")
    return float(solver.e_tot), gradient.tolist()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--basis", default="cc-pVTZ")
    parser.add_argument("--threads", type=int, default=1)
    args = parser.parse_args()
    if args.threads <= 0:
        parser.error("threads must be positive")
    lib.num_threads(args.threads)
    grid = {
        "train": [0.50, 0.60, 0.70, 0.80, 0.90, 1.05, 1.20, 1.40, 1.65, 1.90],
        "validation": [0.55, 0.65, 0.74, 0.85, 0.975, 1.125, 1.30, 1.525, 1.775],
        "extrapolation": [0.45, 2.10, 2.50, 3.00],
    }
    samples = []
    for split, distances in grid.items():
        for distance in distances:
            energy, gradient = reference(distance, args.basis)
            samples.append({
                "xyz": f"2\nindependent FCI H2\nH 0 0 0\nH {distance:.12f} 0 0\n",
                "charge": 0, "split": split, "bond_length_angstrom": distance,
                "energy_hartree": energy, "gradient_hartree_per_bohr": gradient,
            })
            print(f"R={distance:.6f} split={split} E={energy:.14f}", flush=True)
    data = {
        "schema": "gfn1-rs-energy-training-v1",
        "energy_units": "hartree", "coordinate_units": "angstrom",
        "energy_definition": "mermin_free", "electronic_temperature_K": 0.0,
        "provenance": "Independently generated by scripts/generate_h2_fci.py; full-active-space CASCI/FCI with analytic nuclear gradients; nonrelativistic Born-Oppenheimer H2",
        "reference_method": f"FCI/{args.basis}", "independent_reference": True,
        "license_spdx": "CC0-1.0",
        "reference_citations": ["10.1063/5.0006074", "10.1063/1.456153"],
        "generator_versions": {"python": platform.python_version(), **{
            name: importlib.metadata.version(name) for name in ["pyscf", "numpy", "scipy"]}},
        "numerical_settings": {"rhf_energy_tolerance_hartree": 1e-12,
                               "fci_tolerance": 1e-12, "threads": args.threads},
        "samples": samples,
    }
    encoded = (json.dumps(data, indent=2, sort_keys=True) + "\n").encode("ascii")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(encoded)
    print(f"dataset_sha256 {hashlib.sha256(encoded).hexdigest()}")


if __name__ == "__main__":
    main()
