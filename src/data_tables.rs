/// Map a symmetric angular-momentum pair `(l1, l2)` (l in {0=s, 1=p, 2=d}) to
/// the index into a [`GFN_SPIN_CONSTANTS`] row. Mirrors tblite's `lidx`
/// (`[ss, sp, pp, sd, pd, dd]`).
#[inline]
fn spin_constant_pair_index(l1: usize, l2: usize) -> Option<usize> {
    let (a, b) = if l1 <= l2 { (l1, l2) } else { (l2, l1) };
    match (a, b) {
        (0, 0) => Some(0), // ss
        (0, 1) => Some(1), // sp
        (1, 1) => Some(2), // pp
        (0, 2) => Some(3), // sd
        (1, 2) => Some(4), // pd
        (2, 2) => Some(5), // dd
        _ => None,         // f/g shells carry no spin constant
    }
}

/// GFN spin constant `W_{l1 l2}` for element `z` and the (symmetric) shell
/// angular-momentum pair `(l1, l2)`. Returns 0 for elements/shell pairs without
/// a tabulated value (e.g. f/g shells, or Z outside 1..=86), which makes the
/// spin term vanish there rather than erroring. Source: tblite `spin.f90`.
pub fn gfn_spin_constant(l1: usize, l2: usize, z: u8) -> f64 {
    if z == 0 || z as usize > GFN_SPIN_CONSTANTS.len() {
        return 0.0;
    }
    match spin_constant_pair_index(l1, l2) {
        Some(idx) => GFN_SPIN_CONSTANTS[(z - 1) as usize][idx],
        None => 0.0,
    }
}

