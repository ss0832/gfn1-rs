pub fn pauling_en(z: u8) -> Result<f64> {
    // Entries above Rn (Z = 86) are 1.50 placeholders, not data. The GFN1
    // parametrization ends at Z = 86 anyway, so reject instead of silently
    // feeding fabricated electronegativities into the H0 scaling.
    if z > 86 {
        return Err(Gfn1Error::InvalidInput(format!(
            "no Pauling electronegativity for Z={z}: the GFN1 parametrization and its \
             electronegativity table end at Rn (Z=86)"
        )));
    }
    let value = PAULING_EN.get(z as usize).copied().unwrap_or(-1.0);
    if value < 0.0 {
        return Err(Gfn1Error::InvalidInput(format!(
            "no Pauling electronegativity for Z={z}"
        )));
    }
    Ok(value)
}

pub fn atomic_radius_bohr(z: u8) -> Result<f64> {
    let value = XTB_ATOMIC_RADII_ANGSTROM
        .get(z as usize)
        .copied()
        .unwrap_or(0.0);
    if value <= 0.0 {
        return Err(Gfn1Error::InvalidInput(format!(
            "no xTB atomic radius for Z={z}"
        )));
    }
    Ok(value * ANGSTROM_TO_BOHR)
}

pub fn covalent_radius_d3_bohr(z: u8) -> Result<f64> {
    let value = MCTC_COVALENT_RADII_2009_ANGSTROM
        .get(z as usize)
        .copied()
        .unwrap_or(0.0);
    if value <= 0.0 {
        return Err(Gfn1Error::InvalidInput(format!(
            "no mctc covalent radius for Z={z}"
        )));
    }
    Ok((4.0 / 3.0) * value * ANGSTROM_TO_BOHR)
}

pub fn multipole_valence_cn(z: u8) -> f64 {
    XTB_MULTIPOLE_VALENCE_CN
        .get(z as usize)
        .copied()
        .unwrap_or(0.0)
}

pub fn multipole_radius_bohr(z: u8) -> f64 {
    XTB_MULTIPOLE_RADII_BOHR
        .get(z as usize)
        .copied()
        .unwrap_or(5.0)
}

pub fn multipole_valence_cn_checked(z: u8) -> Result<f64> {
    let value = XTB_MULTIPOLE_VALENCE_CN
        .get(z as usize)
        .copied()
        .unwrap_or(0.0);
    if z == 0 || z as usize > MAX_GFN1_Z || value <= 0.0 || !value.is_finite() {
        return Err(Gfn1Error::InvalidInput(format!(
            "no xTB multipole valence CN for Z={z}"
        )));
    }
    Ok(value)
}

pub fn multipole_radius_bohr_checked(z: u8) -> Result<f64> {
    let value = XTB_MULTIPOLE_RADII_BOHR
        .get(z as usize)
        .copied()
        .unwrap_or(0.0);
    if z == 0 || z as usize > MAX_GFN1_Z || value <= 0.0 || !value.is_finite() {
        return Err(Gfn1Error::InvalidInput(format!(
            "no xTB multipole radius for Z={z}"
        )));
    }
    Ok(value)
}

